/** Every locale must provide exactly these keys. */
export type Dict = typeof en;

type Join<P extends string, K extends string> = P extends "" ? K : `${P}.${K}`;

type LeafKeys<T, P extends string = ""> = {
  [K in keyof T & string]: T[K] extends string
    ? Join<P, K>
    : T[K] extends unknown[]
      ? never
      : T[K] extends object
        ? LeafKeys<T[K], Join<P, K>>
        : never;
}[keyof T & string];

/** The dot-separated addresses `t()` accepts, e.g. `"hero.ctaShop"`. */
export type TranslationKey = LeafKeys<Dict>;

/** Interpolation values for `{name}` placeholders inside a string. */
export type Params = Record<string, string | number>;
